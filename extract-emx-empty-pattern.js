/**
 * One-off: extract the EMX-1's canonical empty pattern block from a real
 * hardware SmartCard dump and write it as a test fixture.
 *
 * Run:  node extract-emx-empty-pattern.js
 *
 * The source card (test-data/emx/BEST.EMX) is a factory card already in the
 * repo. Both outputs ARE committed, so the test suite needs neither the card
 * nor network access:
 *
 *   tests/fixtures/emx-empty-pattern.bin  – the raw 4806-byte block
 *   src/emx-empty-pattern.js              – the same bytes as base64
 *
 * Two copies because electron-builder excludes `tests/**` from the package
 * (package.json `build.files`), so production code cannot read the .bin at
 * runtime. `emx-slot-mapping.test.js` asserts the two are byte-identical, so
 * they cannot drift apart.
 *
 * Ground truth (see docs/superpowers/specs/2026-08-12-emx-slot-mapping-design.md):
 * BEST.EMX's most frequent pattern block occurs 5x, is named "Init    " and
 * carries factory settings — 120.0 BPM, no swing, 16th beat. DA4TOFE.EMX's
 * most frequent block occurs 114x with a blank name but a foreign user's
 * preferences (130 BPM, swing 6, 16-triplet), so the factory block is the one
 * worth keeping. Only the name is changed: a card written by this tool is a
 * saved user card, not a factory card, and the hardware writes 8x 0x20 into
 * the name of a slot it considers unused.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'test-data', 'emx', 'BEST.EMX');
const OTHER = path.join(__dirname, 'test-data', 'emx', 'DA4TOFE.EMX');
const OUT = path.join(__dirname, 'tests', 'fixtures');

const CARD_SIZE = 1736704;
const PAT_BASE = 0x200, PAT_SIZE = 4806, PAT_COUNT = 256;
const NAME_LEN = 8;

/** Return the byte block that occurs most often in `blocks`. */
function modal(blocks) {
  const counts = new Map();
  for (const b of blocks) {
    const k = b.toString('base64');
    counts.set(k, (counts.get(k) || 0) + 1);
  }
  const [k, n] = [...counts].sort((a, b) => b[1] - a[1])[0];
  return { block: Buffer.from(k, 'base64'), count: n, total: blocks.length };
}

function blocksOf(buf) {
  const out = [];
  for (let i = 0; i < PAT_COUNT; i++) {
    out.push(buf.slice(PAT_BASE + i * PAT_SIZE, PAT_BASE + (i + 1) * PAT_SIZE));
  }
  return out;
}

function countDiff(a, b) {
  let n = 0;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) n++;
  return n;
}

function main() {
  const buf = fs.readFileSync(SRC);
  if (buf.length !== CARD_SIZE) {
    throw new Error(`${SRC} is ${buf.length} bytes, expected ${CARD_SIZE}`);
  }

  const pat = modal(blocksOf(buf));
  console.log(`BEST.EMX: canonical block occurs ${pat.count}x of ${pat.total}`);
  if (pat.count !== 5) {
    throw new Error(`expected the factory Init block 5x, got ${pat.count}x — wrong card?`);
  }

  const name = pat.block.slice(0, NAME_LEN).toString('latin1');
  const tempo = pat.block.readUInt16BE(0x08) / 128;
  const swing = pat.block.readUInt8(0x0A);
  const beat = pat.block.readUInt8(0x0C);
  console.log(`  name=${JSON.stringify(name)} tempo=${tempo} swing=${swing} beat=${beat}`);
  if (name !== 'Init    ') throw new Error(`expected name "Init    ", got ${JSON.stringify(name)}`);
  if (tempo !== 120) throw new Error(`expected 120.0 BPM, got ${tempo}`);
  if (swing !== 0) throw new Error(`expected no swing, got ${swing}`);
  if (beat !== 0) throw new Error(`expected 16th beat, got ${beat}`);

  // Cross-check against the other card's unused-slot block. The spec measured
  // 74 differing bytes between the two; a wildly different number means one of
  // the two blocks is not what we think it is.
  const otherBuf = fs.readFileSync(OTHER);
  const other = modal(blocksOf(otherBuf));
  const delta = countDiff(pat.block, other.block);
  console.log(`  vs DA4TOFE.EMX unused block (${other.count}x): ${delta} of ${PAT_SIZE} bytes differ`);
  if (delta !== 74) throw new Error(`expected 74 differing bytes, got ${delta}`);

  // The one edit: blank the name. Everything else stays factory-identical.
  const fixture = Buffer.from(pat.block);
  fixture.fill(0x20, 0, NAME_LEN);
  if (countDiff(fixture, pat.block) !== 4) {
    throw new Error('blanking the name should change exactly the 4 non-space name bytes');
  }

  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'emx-empty-pattern.bin'), fixture);
  console.log(`wrote tests/fixtures/emx-empty-pattern.bin (${fixture.length} B)`);

  const b64 = fixture.toString('base64');
  const wrapped = b64.replace(/(.{76})/g, '$1\n').replace(/\n$/, '');
  const module = `/**
 * The EMX-1's canonical empty pattern block (4806 bytes), base64-encoded.
 *
 * GENERATED by extract-emx-empty-pattern.js from test-data/emx/BEST.EMX —
 * do not edit by hand. Re-run that script to regenerate.
 *
 * The factory Init block with its name blanked to 8x 0x20, which is how the
 * hardware itself marks an unused slot on a user-saved card. Embedded rather
 * than read from tests/fixtures/emx-empty-pattern.bin because the packaged
 * app does not ship the tests directory.
 */
'use strict';

const EMX_EMPTY_PATTERN_B64 = [
${wrapped.split('\n').map(l => `  '${l}',`).join('\n')}
].join('');

module.exports = { EMX_EMPTY_PATTERN_B64 };
`;
  fs.writeFileSync(path.join(__dirname, 'src', 'emx-empty-pattern.js'), module);
  console.log(`wrote src/emx-empty-pattern.js (${b64.length} B base64)`);
}

main();
